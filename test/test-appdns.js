/**
 * test/test-appdns.js - an app's own DNS servers are written into its jail,
 * written again after the jailer's copy replaces them, and taken out again,
 * and only apps with a jail are offered
 *
 * Strict ES5: runs on node 0.12.
 */
var assert = require('assert');
var fs = require('fs');
var os = require('os');
var path = require('path');
var appDns = require('../server/lib/appdns');

console.log('Running test-appdns.js ...');

var CONNMAN = '# Generated by Connection Manager\nnameserver ::1\nnameserver 127.0.0.1\n';

function mkdirs(p) {
  if (fs.existsSync(p)) return;
  mkdirs(path.dirname(p));
  fs.mkdirSync(p);
}

var dir = fs.mkdtempSync ? fs.mkdtempSync(path.join(os.tmpdir(), 'appdns-')) : path.join(os.tmpdir(), 'appdns-' + process.pid);
mkdirs(dir);
var jails = path.join(dir, 'jail');
var hostResolv = path.join(dir, 'resolv.conf');
fs.writeFileSync(hostResolv, CONNMAN);

// What the jailer does at a launch: a fresh copy of the TV's file.
function makeJail(id) {
  mkdirs(path.join(jails, id, 'etc'));
  fs.writeFileSync(path.join(jails, id, 'etc', 'resolv.conf'), CONNMAN);
}
function jailResolv(id) { return fs.readFileSync(path.join(jails, id, 'etc', 'resolv.conf'), 'utf8'); }

// fs.watch stood in for: each watch is kept, and fired by hand.
var watches = [];
function fakeWatch(p, cb) {
  var w = { path: p, cb: cb, closed: false, close: function () { this.closed = true; }, on: function () {} };
  watches.push(w);
  return w;
}
function fire(p, name) {
  var n = 0;
  watches.forEach(function (w) { if (!w.closed && w.path === p) { w.cb('change', name); n++; } });
  return n;
}

var INSTALLED = [
  { id: 'youtube.leanback.v4', title: 'YouTube' },
  { id: 'netflix', title: 'Netflix' },
  { id: 'com.webos.app.browser', title: 'Web Browser' },
  { id: 'com.lg.weather', title: 'Weather' }
];
function luna(uri, params, cb) {
  var r = { returnValue: true };
  if (uri === 'com.webos.applicationManager/listApps') r.apps = INSTALLED;
  process.nextTick(function () { cb(r); });
}

makeJail('youtube.leanback.v4');
makeJail('netflix');
makeJail('lg.thinqai.adapter');      // a jail with no app: not offered
mkdirs(path.join(jails, 'wap'));     // a jail without etc: not offered

// lib/doh stood in for: the addresses it is told to answer on, and an error
// for each, as its status gives.
var forwarder = {
  served: {},
  errors: {},
  serve: function (map) { this.served = map; },
  stop: function () { this.served = {}; },
  status: function () {
    var out = {};
    for (var a in this.served) out[a] = { url: this.served[a], error: this.errors[this.served[a]] || null };
    return out;
  }
};

appDns.init({ luna: luna, stateDir: dir, jailRoot: jails, hostResolv: hostResolv, watch: fakeWatch, doh: forwarder });

var steps = [];
function step(name, fn) { steps.push({ name: name, fn: fn }); }

step('addresses are checked, kept once each, and at most three', function (done) {
  assert.deepEqual(appDns.parseSetting('1.1.1.1, 1.0.0.1').servers, ['1.1.1.1', '1.0.0.1']);
  assert.deepEqual(appDns.parseSetting(['2606:4700:4700::1111', '1.1.1.1', '1.1.1.1']).servers, ['2606:4700:4700::1111', '1.1.1.1']);
  assert.deepEqual(appDns.parseSetting('1.1.1.1، 1.0.0.1').servers, ['1.1.1.1', '1.0.0.1']);
  assert.deepEqual(appDns.parseSetting('').servers, []);
  assert.deepEqual(appDns.parseSetting(null).servers, []);
  assert.ok(appDns.parseSetting('dns.google').error);
  assert.ok(appDns.parseSetting('1.1.1.1 1.0.0.1 8.8.8.8 9.9.9.9').error);
  done();
});

step('a DNS-over-HTTPS address is taken on its own, and only over https', function (done) {
  assert.equal(appDns.parseSetting(' https://dns.nextdns.io/abc123 ').doh, 'https://dns.nextdns.io/abc123');
  assert.equal(appDns.parseSetting(['https://cloudflare-dns.com/dns-query']).doh, 'https://cloudflare-dns.com/dns-query');
  assert.ok(appDns.parseSetting('https://dns.nextdns.io/abc123, 1.1.1.1').error);
  assert.ok(appDns.parseSetting('http://dns.nextdns.io/abc123').error);
  assert.ok(appDns.parseSetting('tls://dns.nextdns.io').error);
  assert.ok(appDns.parseSetting('https://').error);
  assert.ok(appDns.parseSetting('https://user@dns.example/q').error);
  done();
});

step('only installed apps with a jail are offered, by title', function (done) {
  appDns.getAppDns(function (r) {
    assert.ok(r.ok && r.supported);
    assert.deepEqual(r.apps.map(function (a) { return a.id; }), ['netflix', 'youtube.leanback.v4']);
    assert.deepEqual(r.apps[1].servers, []);
    done();
  });
});

step('an app without a jail, or a path for an id, is refused', function (done) {
  appDns.setAppDns('com.lg.weather', '1.1.1.1', function (r) {
    assert.ok(!r.ok);
    appDns.setAppDns('../netflix', '1.1.1.1', function (r2) {
      assert.ok(!r2.ok);
      appDns.setAppDns('youtube.leanback.v4', '1.1.1.1, nonsense', function (r3) {
        assert.ok(!r3.ok);
        assert.equal(jailResolv('youtube.leanback.v4'), CONNMAN);
        done();
      });
    });
  });
});

step('setting servers writes them into the jail and keeps them', function (done) {
  appDns.setAppDns('youtube.leanback.v4', '1.1.1.1, 1.0.0.1', function (r) {
    assert.ok(r.ok);
    assert.equal(jailResolv('youtube.leanback.v4'), appDns.resolvText(['1.1.1.1', '1.0.0.1']));
    assert.equal(jailResolv('netflix'), CONNMAN);
    // The boot hook's copy, for launches before the server is up.
    assert.equal(fs.readFileSync(path.join(dir, 'appdns', 'youtube.leanback.v4.resolv'), 'utf8'),
      appDns.resolvText(['1.1.1.1', '1.0.0.1']));
    assert.deepEqual(fs.readdirSync(path.join(dir, 'appdns')), ['youtube.leanback.v4.resolv']);
    appDns.getAppDns(function (g) {
      var yt = g.apps.filter(function (a) { return a.id === 'youtube.leanback.v4'; })[0];
      assert.deepEqual(yt.servers, ['1.1.1.1', '1.0.0.1']);
      done();
    });
  });
});

step('the jailer\'s copy at a launch is replaced once the watch sees it', function (done) {
  makeJail('youtube.leanback.v4');
  assert.equal(jailResolv('youtube.leanback.v4'), CONNMAN);
  assert.ok(fire(path.join(jails, 'youtube.leanback.v4', 'etc'), 'resolv.conf') > 0);
  assert.equal(jailResolv('youtube.leanback.v4'), appDns.resolvText(['1.1.1.1', '1.0.0.1']));
  done();
});

step('a reset seen on the jail itself watches etc again and replaces the copy', function (done) {
  var etc = path.join(jails, 'youtube.leanback.v4', 'etc');
  var before = watches.filter(function (w) { return !w.closed && w.path === etc; }).length;
  makeJail('youtube.leanback.v4');
  fire(path.join(jails, 'youtube.leanback.v4'), 'jail-reset.6.5.3-47');
  assert.equal(jailResolv('youtube.leanback.v4'), appDns.resolvText(['1.1.1.1', '1.0.0.1']));
  assert.equal(watches.filter(function (w) { return !w.closed && w.path === etc; }).length, before);
  done();
});

step('clearing puts back the TV\'s copy and stops watching', function (done) {
  appDns.setAppDns('youtube.leanback.v4', '', function (r) {
    assert.ok(r.ok);
    assert.equal(jailResolv('youtube.leanback.v4'), CONNMAN);
    assert.deepEqual(fs.readdirSync(path.join(dir, 'appdns')), []);
    makeJail('youtube.leanback.v4');
    assert.equal(fire(path.join(jails, 'youtube.leanback.v4', 'etc'), 'resolv.conf'), 0);
    assert.equal(jailResolv('youtube.leanback.v4'), CONNMAN);
    done();
  });
});

step('a DNS-over-HTTPS address points the app at a forwarder on the TV, one per address', function (done) {
  var NEXT = 'https://dns.nextdns.io/abc123';
  var CF = 'https://cloudflare-dns.com/dns-query';
  appDns.setAppDns('netflix', NEXT, function (r) {
    assert.ok(r.ok);
    assert.equal(r.doh, NEXT);
    assert.deepEqual(forwarder.served, { '127.0.53.1': NEXT });
    assert.equal(jailResolv('netflix'), appDns.resolvText(['127.0.53.1']));
    forwarder.errors[NEXT] = 'HTTP 403';
    appDns.getAppDns(function (g) {
      var nf = g.apps.filter(function (a) { return a.id === 'netflix'; })[0];
      assert.equal(nf.doh, NEXT);
      assert.deepEqual(nf.servers, []);
      assert.equal(nf.dohError, 'HTTP 403');
      // A second address sorts first, so Netflix's forwarder moves and its jail follows.
      appDns.setAppDns('youtube.leanback.v4', CF, function (r2) {
        assert.ok(r2.ok);
        assert.deepEqual(forwarder.served, { '127.0.53.1': CF, '127.0.53.2': NEXT });
        assert.equal(jailResolv('youtube.leanback.v4'), appDns.resolvText(['127.0.53.1']));
        assert.equal(jailResolv('netflix'), appDns.resolvText(['127.0.53.2']));
        assert.equal(fs.readFileSync(path.join(dir, 'appdns', 'netflix.resolv'), 'utf8'), appDns.resolvText(['127.0.53.2']));
        appDns.setAppDns('youtube.leanback.v4', '', function () {
          appDns.setAppDns('netflix', '', function () {
            assert.deepEqual(forwarder.served, {});
            assert.equal(jailResolv('netflix'), CONNMAN);
            done();
          });
        });
      });
    });
  });
});

step('at start, a saved app is set again, and one whose jail comes later once it appears', function (done) {
  fs.writeFileSync(path.join(dir, 'appdns.json'), JSON.stringify({ apps: { netflix: ['9.9.9.9'], 'com.lg.weather': ['1.1.1.1'] } }));
  appDns.start();
  assert.equal(jailResolv('netflix'), appDns.resolvText(['9.9.9.9']));
  assert.deepEqual(fs.readdirSync(path.join(dir, 'appdns')).sort(), ['com.lg.weather.resolv', 'netflix.resolv']);
  makeJail('com.lg.weather');
  fire(jails, 'com.lg.weather');
  assert.equal(jailResolv('com.lg.weather'), appDns.resolvText(['1.1.1.1']));
  appDns.stop();
  assert.equal(watches.filter(function (w) { return !w.closed; }).length, 0);
  done();
});

step('a TV without jails offers nothing', function (done) {
  appDns.init({ luna: luna, stateDir: dir, jailRoot: path.join(dir, 'none'), hostResolv: hostResolv, watch: fakeWatch });
  appDns.getAppDns(function (r) {
    assert.ok(r.ok && !r.supported);
    assert.deepEqual(r.apps, []);
    done();
  });
});

(function run(i) {
  if (i >= steps.length) {
    console.log('test-appdns.js: all ' + steps.length + ' passed');
    return;
  }
  steps[i].fn(function () { console.log('  ok - ' + steps[i].name); run(i + 1); });
})(0);
